from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

RiskLevel = Literal["low", "moderate", "high", "critical"]
_KEY = r"^[A-Za-z0-9_-]{8,64}$"


class Compose(BaseModel):
    location_id: int
    risk_level: RiskLevel
    message: str = Field(min_length=1, max_length=200)

    @field_validator("message")
    @classmethod
    def _strip(cls, v: str) -> str:
        v = " ".join(v.split())
        if not v:
            raise ValueError("Message must not be blank")
        return v


class PreviewRequest(Compose):
    # Set to preview a single test message to one registered number instead of a broadcast.
    subscriber_id: int | None = None


class SendBroadcast(Compose):
    # Generated by the UI when the confirmation step opens. A retry or double-click with
    # the same key returns the original send instead of texting everyone again.
    idempotency_key: str = Field(pattern=_KEY)
    confirm: bool = False
    expected_recipient_count: int = Field(ge=0)


class SendTest(Compose):
    subscriber_id: int
    idempotency_key: str = Field(pattern=_KEY)
    confirm: bool = False


class PreviewRecipient(BaseModel):
    subscriber_id: int
    name: str
    phone_masked: str


class Preview(BaseModel):
    body: str
    length: int
    segments: int
    recipient_count: int
    recipients: list[PreviewRecipient]
    skipped_not_allowlisted: int
    can_send: bool
    blocking_reasons: list[str]


class ProviderStatus(BaseModel):
    provider: str
    environment: str
    real: bool
    configured: bool
    missing: list[str]
    broadcast_enabled: bool
    sender_id_set: bool
    delivery_reports_enabled: bool
    stop_reply_enabled: bool
    real_test_accepted: bool  # a real test SMS has been accepted by this provider/environment
    group_broadcast_unlocked: bool


class MessageOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    phone_masked: str
    submission_status: str
    submission_detail: str
    provider_message_id: str | None
    provider_status: str
    provider_status_code: int | None
    cost: str | None
    submitted_at: datetime | None
    delivery_status: str
    delivery_reported_at: datetime | None
    failure_reason: str


class BroadcastOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    kind: str
    location_id: int | None
    risk_level: str
    body: str
    segments: int
    recipient_count: int
    provider: str
    environment: str
    status: str
    created_by: int | None
    created_at: datetime
    completed_at: datetime | None
    accepted_count: int = 0
    delivered_count: int = 0
    delivery_failed_count: int = 0


class BroadcastDetail(BroadcastOut):
    messages: list[MessageOut]
    replayed: bool = False  # true when this is an earlier send returned for a repeated key
